import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { PDFArray, PDFDict, PDFDocument, PDFHexString, PDFName, PDFString, StandardFonts } from 'pdf-lib'
import { useFixedZoom, clickFileAction } from './helpers/reader'

test('adds and formats inline Chinese text, edits/moves it, restores it and exports an embedded font', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const source = await PDFDocument.create()
  const sheet = source.addPage([612, 792])
  const helvetica = await source.embedFont(StandardFonts.Helvetica)
  sheet.drawText('Inline text acceptance paper', { x: 60, y: 725, font: helvetica, size: 20 })
  await page.goto('/')
  await expect(page.locator('#page-1 .textLayer')).toBeVisible()
  await page.locator('input[type=file][accept="application/pdf,.pdf"]').setInputFiles({ name: 'text-paper.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await source.save()) })
  await expect(page.locator('#page-1 .textLayer')).toContainText('Inline text acceptance paper')
  await useFixedZoom(page)
  await page.getByRole('button', { name: '添加文字', exact: true }).click()
  await expect(page.locator('.text-format-bar')).toBeVisible()
  await page.locator('#page-1').click({ position: { x: 75, y: 180 } })
  const editor = page.getByRole('textbox', { name: '页面文字', exact: true })
  await expect(editor).toBeVisible()
  const content = '中文论文批注，直接添加文字。\nInline text with embedded fonts.'
  await editor.fill(content)
  await page.getByLabel('字号', { exact: true }).fill('24')
  await page.getByLabel('文字颜色', { exact: true }).fill('#a73542')
  await page.getByRole('button', { name: '粗体', exact: true }).click()
  await page.getByRole('button', { name: '斜体', exact: true }).click()
  await page.getByRole('button', { name: '文字下划线', exact: true }).click()
  await page.getByRole('button', { name: '居中对齐', exact: true }).click()
  await page.getByLabel('文字行距').selectOption('1.6')
  await expect(editor).toHaveCSS('font-size', '24px')
  await expect(editor).toHaveCSS('color', 'rgb(167, 53, 66)')
  await expect(editor).toHaveCSS('font-weight', '700')
  await expect(editor).toHaveCSS('font-style', 'italic')
  await page.getByRole('button', { name: '完成', exact: true }).click()
  const mark = page.locator('.pdf-mark-text')
  await expect(mark).toHaveCount(1)
  await expect(mark.locator('text')).toContainText('中文论文批注')
  await expect(page.locator('.pdf-mark-outline')).toHaveCount(0)
  await expect(page.locator('.text-format-bar')).toHaveCount(0)
  const original = await mark.boundingBox()
  expect(original).toBeTruthy()
  await page.mouse.move(original!.x + 8, original!.y + 8)
  await page.mouse.down()
  await page.mouse.move(original!.x + 48, original!.y + 48, { steps: 10 })
  await page.mouse.up()
  await expect.poll(async () => (await mark.boundingBox())!.x).toBeCloseTo(original!.x + 40, 0)
  await expect.poll(async () => (await mark.boundingBox())!.y).toBeCloseTo(original!.y + 40, 0)
  await mark.dblclick({ position: { x: 12, y: 12 } })
  await expect(editor).toHaveValue(content)
  await editor.fill(content + '\n修改后的文字。')
  await editor.press('Control+Enter')
  await expect(editor).toHaveCount(0)
  await expect(mark.locator('text')).toContainText('修改后的文字')
  await clickFileAction(page, '撤销')
  await expect(mark.locator('text')).not.toContainText('修改后的文字')
  await clickFileAction(page, '重做')
  await expect(mark.locator('text')).toContainText('修改后的文字')
  await expect(page.locator('.save-state')).toHaveText('已保存到本机')
  await page.reload()
  await expect(mark.locator('text')).toContainText('修改后的文字')
  await expect(mark.locator('text')).toHaveAttribute('fill', '#a73542')
  const downloadEvent = page.waitForEvent('download')
  await clickFileAction(page, '导出 PDF')
  const download = await downloadEvent
  const output = await PDFDocument.load(await readFile((await download.path())!))
  const annotations = output.getPages()[0].node.lookup(PDFName.of('Annots'), PDFArray)
  const freeText = annotations.asArray().map(ref => output.context.lookup(ref, PDFDict)).find(dict => dict.get(PDFName.of('Subtype'))?.toString() === '/FreeText')
  expect(freeText).toBeTruthy()
  const contents = freeText!.lookup(PDFName.of('Contents'))
  expect(contents instanceof PDFHexString || contents instanceof PDFString).toBeTruthy()
  expect((contents as PDFHexString).decodeText()).toContain('修改后的文字')
  expect(freeText!.has(PDFName.of('AP'))).toBe(true)
  expect(freeText!.has(PDFName.of('DR'))).toBe(true)
  expect(errors).toEqual([])
})

test('uses real system fonts and imports a local font file without losing text on document switch', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#page-1 .textLayer')).toBeVisible()
  await page.getByRole('button', { name: '添加文字', exact: true }).click()
  const fonts = await page.request.get('/api/fonts').then(response => response.json()) as { id: string; fullName: string; family: string; postscriptName: string }[]
  expect(fonts.length).toBeGreaterThan(0)
  const latin = fonts.find(font => font.postscriptName === 'ArialMT') ?? fonts.find(font => /Arial|Helvetica/.test(font.family)) ?? fonts[0]
  await page.getByLabel('字体', { exact: true }).selectOption(latin.id)
  await page.locator('#page-1').click({ position: { x: 80, y: 200 } })
  await page.getByRole('textbox', { name: '页面文字', exact: true }).fill('Real local font text')
  await expect(page.getByLabel('字体', { exact: true })).toHaveValue(latin.id)
  // A small real OS font is imported through the same file picker the user sees.
  const fontBytes = await page.request.get(`/api/fonts/${latin.id}`).then(response => response.body())
  await page.getByLabel('导入字体文件', { exact: true }).setInputFiles({ name: 'local-test.ttf', mimeType: 'font/ttf', buffer: fontBytes })
  await expect.poll(() => page.getByLabel('字体', { exact: true }).inputValue()).toMatch(/^imported-/)
  await page.getByRole('button', { name: '完成', exact: true }).click()
  const beforeCount = await page.locator('.pdf-mark-text').count()
  await page.getByRole('button', { name: '添加文字', exact: true }).click()
  await page.locator('#page-1').click({ position: { x: 90, y: 270 } })
  await page.getByRole('textbox', { name: '页面文字', exact: true }).fill('Cancel this draft')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.pdf-mark-text')).toHaveCount(beforeCount)
  const source = await PDFDocument.create(); source.addPage([612, 792])
  await page.locator('input[type=file][accept="application/pdf,.pdf"]').setInputFiles({ name: 'second-text-file.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await source.save()) })
  await expect(page.locator('.pdf-mark-text')).toHaveCount(0)
  await page.getByRole('button', { name: '最近阅读', exact: true }).click()
  await page.locator('.recent-list').getByRole('button').filter({ hasText: 'The art of paying attention.pdf' }).click()
  await expect(page.locator('.pdf-mark-text text')).toContainText('Real local font text')
})
